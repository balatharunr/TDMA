#!/usr/bin/env python3
"""Division 6: generate the EMANE scenario (every config file) for the radios of a Part 1 ``schedule.json``.

Standard library only, so it runs and is tested on Windows; the container runs the very same script.

    python emane/gen/generate_scenario.py --schedule results/grid16_300m.schedule.json --out emane/scenario/grid16_300m

Writes into --out:
    nemmap.json         node name -> NEM id, network namespace, backplane IP, radio IP (natural order, NEM ids from 1)
    platformNN.xml      one emulator instance per radio: NEM id, OTA + event channels, control port, TUN device address
    tdmanem.xml         the radio stack shared by every radio: transport + TDMA MAC + PHY
    tdmaradiomodel.xml  the TDMA radio model (MAC) parameters, including the required PCR curve
    transvirtual.xml    the virtual transport (the TUN/TAP device "emane0")
    links.csv           the links of the 500 m radio graph, copied from schedule.json (emane/bridge/pathloss.py mirrors them)

Naming rule (Section "Part 2 architecture" of the guide):
    Node_XX (natural-order index i) -> NEM id i -> netns nodeXX -> backchan0 10.99.0.i -> emane0 10.100.0.i
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SCHEMA = "tdma-schedule/v1"
BACKPLANE_NET = "10.99.0"      # backchan0 addresses are 10.99.0.<nem>; the bridge itself is 10.99.0.254
RADIO_NET = "10.100.0"         # emane0 addresses are 10.100.0.<nem>
MAX_NEMS = 253                 # one /24 per network, .254 is the bridge
OTA_GROUP = "224.1.2.8:45702"
EVENT_GROUP = "224.1.2.8:45703"
CONTROL_PORT = 47000
DEFAULT_SUBID = 7
DEFAULT_PCR_URI = "file:///usr/share/emane/xml/models/mac/tdmaeventscheduler/tdmabasemodelpcr.xml"
REQUIRED_KEYS = ("schema", "nodes", "coordinates", "links", "radio_range_m", "frame_length", "node_to_slot")
SHARED_FILES = ("tdmanem.xml", "tdmaradiomodel.xml", "transvirtual.xml")


class ScenarioError(Exception):
    """A problem with the input schedule or the requested scenario (reported without a traceback)."""


def natural_key(name):
    """Sort key so that Node_2 < Node_10 (same rule as tdma_brain.io_utils.natural_key, stdlib only)."""
    return [int(part) if part.isdigit() else part.lower() for part in re.split(r"(\d+)", str(name))]


def load_schedule(path: Path) -> dict:
    """Read and validate a Part 1 schedule.json (the tdma-schedule/v1 contract, guide Section 4.4)."""
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ScenarioError(f"cannot read schedule {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise ScenarioError(f"{path}: schedule.json must be a JSON object")
    missing = [key for key in REQUIRED_KEYS if key not in data]
    if missing:
        raise ScenarioError(f"{path}: missing keys {', '.join(missing)}")
    if data["schema"] != SCHEMA:
        raise ScenarioError(f"{path}: schema is {data['schema']!r}, expected {SCHEMA!r}")
    if not data["nodes"]:
        raise ScenarioError(f"{path}: no nodes")
    unknown = [n for pair in data["links"] for n in pair if n not in data["nodes"]]
    if unknown:
        raise ScenarioError(f"{path}: links mention unknown nodes {sorted(set(unknown))}")
    return data


def id_width(n: int) -> int:
    """Digits used in nodeXX / platformXX / vethXX names: 2, or more for 100+ radios (lib.sh uses the same rule)."""
    return max(2, len(str(n)))


def build_nemmap(nodes) -> dict[str, dict]:
    """Node name -> {nem, netns, backchan_ip, radio_ip}, in natural order with NEM ids starting at 1."""
    ordered = sorted(nodes, key=natural_key)
    if len(ordered) > MAX_NEMS:
        raise ScenarioError(f"{len(ordered)} radios, but the 10.99.0.0/24 backplane allows at most {MAX_NEMS}")
    width = id_width(len(ordered))
    # CONCEPT: Identifier mapping (node name <-> NEM id <-> IP) - EMANE only knows NEM ids; everything in Part 2
    # (namespaces, addresses, schedule XML) is derived from this one table.
    return {
        name: {
            "nem": i,
            "netns": f"node{i:0{width}d}",
            "backchan_ip": f"{BACKPLANE_NET}.{i}",
            "radio_ip": f"{RADIO_NET}.{i}",
        }
        for i, name in enumerate(ordered, start=1)
    }


def platform_xml(nem: int, radio_ip: str) -> str:
    """One emulator instance (one emane process) hosting exactly one NEM."""
    # CONCEPT: EMANE XML configuration (platform, NEM, MAC, PHY, transport) - the platform file is the top of the
    # tree: emulator-wide settings (channels, control port) and the NEM it hosts; nem -> mac/phy/transport files.
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE platform SYSTEM "file:///usr/share/emane/dtd/platform.dtd">
<!-- generated by emane/gen/generate_scenario.py (Division 6): one emulator instance = one NEM = one radio -->
<platform>
  <param name="otamanagerchannelenable" value="on"/>
  <param name="otamanagerdevice" value="backchan0"/>
  <param name="otamanagergroup" value="{OTA_GROUP}"/>
  <param name="eventservicegroup" value="{EVENT_GROUP}"/>
  <param name="eventservicedevice" value="backchan0"/>
  <param name="controlportendpoint" value="0.0.0.0:{CONTROL_PORT}"/>
  <nem definition="tdmanem.xml" id="{nem}">
    <transport definition="transvirtual.xml">
      <param name="device" value="emane0"/>
      <param name="address" value="{radio_ip}"/>
      <param name="mask" value="255.255.255.0"/>
    </transport>
  </nem>
</platform>
"""


def nem_xml(subid: int = DEFAULT_SUBID) -> str:
    """The radio stack shared by all radios: transport + TDMA MAC + PHY (emane-guide TDMA template values)."""
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE nem SYSTEM "file:///usr/share/emane/dtd/nem.dtd">
<!-- generated by emane/gen/generate_scenario.py (Division 6): transport + MAC + PHY = one radio -->
<nem>
  <transport definition="transvirtual.xml"/>
  <mac definition="tdmaradiomodel.xml"/>
  <phy>
    <param name="fixedantennagain"       value="0.0"/>
    <param name="fixedantennagainenable" value="on"/>
    <param name="bandwidth"              value="1M"/>
    <!-- all: co-channel energy from other transmitters is counted, so collisions are modelled (Division 8) -->
    <param name="noisemode"              value="all"/>
    <!-- precomputed: pathloss comes only from the events emane/bridge/pathloss.py publishes = our 500 m graph -->
    <param name="propagationmodel"       value="precomputed"/>
    <!-- receiver sensitivity = -174 + 4 + 10*log10(1e6) = -110 dBm -->
    <param name="systemnoisefigure"      value="4.0"/>
    <!-- the same subid on every TDMA NEM, or they cannot hear each other -->
    <param name="subid"                  value="{subid}"/>
    <param name="fading.model"           value="none"/>
  </phy>
</nem>
"""


def mac_xml(pcr_uri: str = DEFAULT_PCR_URI) -> str:
    """The TDMA radio model (MAC). The slot/frame structure is NOT here: it arrives as a schedule event (Division 7)."""
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE mac SYSTEM "file:///usr/share/emane/dtd/mac.dtd">
<!-- generated by emane/gen/generate_scenario.py (Division 6): values from emane-tutorial demo 8 -->
<mac library="tdmaeventschedulerradiomodel">
  <param name="fragmentcheckthreshold"         value="2"/>
  <param name="fragmenttimeoutthreshold"       value="5"/>
  <param name="neighbormetricdeletetime"       value="60.0"/>
  <param name="neighbormetricupdateinterval"   value="1.0"/>
  <param name="queue.aggregationenable"        value="on"/>
  <param name="queue.aggregationslotthreshold" value="90.0"/>
  <param name="queue.depth"                    value="255"/>
  <param name="queue.fragmentationenable"      value="on"/>
  <param name="queue.strictdequeueenable"      value="off"/>
  <!-- REQUIRED: the packet-completion-rate curve (delivery probability vs SINR per data rate) -->
  <param name="pcrcurveuri"                    value="{pcr_uri}"/>
</mac>
"""


def transport_xml() -> str:
    """The virtual transport: creates the TUN/TAP device; device name, address and mask come from the platform file."""
    # CONCEPT: TUN/TAP virtual interfaces - the transport opens /dev/net/tun and creates "emane0" inside the radio's
    # namespace; every IP packet the kernel sends to emane0 becomes an emulated radio transmission.
    return """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE transport SYSTEM "file:///usr/share/emane/dtd/transport.dtd">
<!-- generated by emane/gen/generate_scenario.py (Division 6) -->
<transport library="transvirtual">
  <param name="bitrate"    value="0"/>
  <param name="devicepath" value="/dev/net/tun"/>
</transport>
"""


def links_csv(links) -> str:
    """The radio links, one undirected pair per row, in natural order."""
    rows = sorted((tuple(sorted(pair, key=natural_key)) for pair in links), key=lambda p: (natural_key(p[0]), natural_key(p[1])))
    return "node_a,node_b\n" + "".join(f"{a},{b}\n" for a, b in rows)


def write_scenario(schedule: dict, out_dir: Path, subid: int = DEFAULT_SUBID, pcr_uri: str = DEFAULT_PCR_URI) -> list[Path]:
    """Write every scenario file into out_dir and return the paths written (deterministic: same input, same files)."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    nemmap = build_nemmap(schedule["nodes"])
    width = id_width(len(nemmap))
    written: list[Path] = []

    def put(name: str, text: str) -> None:
        path = out_dir / name
        path.write_text(text, encoding="utf-8", newline="\n")   # LF: the container reads these files
        written.append(path)

    put("nemmap.json", json.dumps(nemmap, indent=2) + "\n")
    for entry in nemmap.values():
        put(f"platform{entry['nem']:0{width}d}.xml", platform_xml(entry["nem"], entry["radio_ip"]))
    put("tdmanem.xml", nem_xml(subid))
    put("tdmaradiomodel.xml", mac_xml(pcr_uri))
    put("transvirtual.xml", transport_xml())
    put("links.csv", links_csv(schedule["links"]))
    return written


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate the EMANE config files (platform/NEM/MAC/transport XML, nemmap.json, links.csv) for every "
                    "radio of a Part 1 schedule.json. Standard library only.")
    parser.add_argument("--schedule", required=True, type=Path, help="schedule.json written by tdma_schedule.py --export-json")
    parser.add_argument("--out", required=True, type=Path, help="scenario directory to write (created if needed)")
    parser.add_argument("--subid", type=int, default=DEFAULT_SUBID, help="PHY subid shared by all radios (default: %(default)s)")
    parser.add_argument("--pcr-uri", default=DEFAULT_PCR_URI, help="URI of the TDMA PCR curve file inside the container")
    return parser


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        schedule = load_schedule(args.schedule)
        written = write_scenario(schedule, args.out, subid=args.subid, pcr_uri=args.pcr_uri)
    except ScenarioError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    n = len(schedule["nodes"])
    print(f"wrote {len(written)} files to {args.out}: {n} platform files + {len(SHARED_FILES)} shared XML + nemmap.json + "
          f"links.csv ({len(schedule['links'])} links, frame length {schedule['frame_length']}, "
          f"radio range {schedule['radio_range_m']} m)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
